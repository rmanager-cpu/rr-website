-- site_tables.sql — the public website's own tables in river-ranch-office (the Supabase hub).
--
-- What's here: the public events calendar (each event series has a page), and job applications from
-- the Careers page. The website logs in as its own role, rr_site_app, which can reach ONLY these
-- tables (plus a read of Venio's spaces list for the "which space?" question). Payroll and Venio's
-- tables are out of its reach.
--
-- Venio feed: every event records whether it closes River Ranch for private events and/or for regular
-- service, and which spaces. The view site_event_closures is what Venio reads to block those dates.
--
-- This file in the repo has REPLACE_WITH_SITE_DB_PASSWORD in it. The paste Alex runs is generated by
-- scripts/make-paste.mjs (with the real password and the starting events), not this file by hand.
-- Safe to run again. Run as the owner; one transaction.

begin;

-- ---------- event pages (one per event series; recurring events share one) ----------
create table if not exists public.site_event_pages (
  id          uuid primary key default gen_random_uuid(),
  slug        text not null unique check (slug ~ '^[a-z0-9][a-z0-9-]{0,80}$'),
  title       text not null check (char_length(title) between 1 and 140),
  summary     text check (summary is null or char_length(summary) <= 400),
  body        text check (body is null or char_length(body) <= 20000),
  hero_image  text check (hero_image is null or char_length(hero_image) <= 400),
  layout      text not null default 'standard' check (layout in ('standard', 'apres', 'collage')),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  updated_by  text
);

-- ---------- events (one row per event or recurring series) ----------
create table if not exists public.site_events (
  id                uuid primary key default gen_random_uuid(),
  page_id           uuid not null references public.site_event_pages(id),
  title             text not null check (char_length(title) between 1 and 140),
  category          text not null check (category in ('happy-hour', 'food', 'music', 'holiday', 'community', 'special', 'off-site')),
  status            text not null default 'published' check (status in ('draft', 'published', 'cancelled')),
  starts_on         date not null,
  ends_on           date,
  start_time        time,
  end_time          time,
  repeat            text not null default 'none' check (repeat in ('none', 'weekly')),
  weekdays          smallint[] not null default '{}',     -- ISO weekdays, 1 = Monday … 7 = Sunday
  skip_holidays     boolean not null default false,       -- skip dates that hold a 'holiday' event
  skip_dates        date[] not null default '{}',
  offsite           boolean not null default false,
  location          text check (location is null or char_length(location) <= 200),
  note              text check (note is null or char_length(note) <= 300),
  ticket_url        text check (ticket_url is null or char_length(ticket_url) <= 400),
  -- Venio feed (asked every time an event is added)
  closed_private    boolean not null default false,       -- no private events that day
  closed_regular    boolean not null default false,       -- regular service closed that day
  venio_spaces      text[] not null default '{}',         -- Venio space names the event uses
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),
  updated_by        text,
  check (ends_on is null or ends_on >= starts_on),
  check (end_time is null or start_time is not null),
  check (repeat = 'none' or array_length(weekdays, 1) >= 1)
);
create index if not exists site_events_dates_idx on public.site_events (starts_on, ends_on) where status <> 'cancelled';

comment on table public.site_events is
  'Public events calendar (website). One row per event or recurring series; every row has a page. closed_private / closed_regular / venio_spaces feed Venio via site_event_closures.';

-- What Venio reads: every live series that closes something, with its date rule.
create or replace view public.site_event_closures as
  select id, title, starts_on, ends_on, repeat, weekdays, skip_holidays, skip_dates,
         start_time, end_time, closed_private, closed_regular, venio_spaces
  from public.site_events
  where status = 'published' and (closed_private or closed_regular);

-- ---------- job applications (Careers page) ----------
create table if not exists public.site_job_applications (
  id          uuid primary key default gen_random_uuid(),
  created_at  timestamptz not null default now(),
  name        text not null check (char_length(btrim(name)) between 1 and 120),
  email       text check (email is null or char_length(email) <= 160),
  phone       text check (phone is null or char_length(phone) <= 40),
  department  text not null check (department in ('Front of house', 'Back of house', 'Lodge staff', 'Maintenance', 'Administrative')),
  status      text not null default 'new' check (status in ('new', 'contacted', 'hired', 'closed')),
  notes       text,
  check (email is not null or phone is not null)
);
create index if not exists site_job_applications_new_idx on public.site_job_applications (created_at desc);

-- ---------- band booking requests (Summer Concert Series page) ----------
create table if not exists public.site_booking_requests (
  id          uuid primary key default gen_random_uuid(),
  created_at  timestamptz not null default now(),
  act_name    text not null check (char_length(btrim(act_name)) between 1 and 140),
  contact     text not null check (char_length(btrim(contact)) between 1 and 120),
  email       text check (email is null or char_length(email) <= 160),
  phone       text check (phone is null or char_length(phone) <= 40),
  genre       text check (genre is null or char_length(genre) <= 140),
  hometown    text check (hometown is null or char_length(hometown) <= 140),
  links       text check (links is null or char_length(links) <= 1000),
  dates       text check (dates is null or char_length(dates) <= 400),
  message     text check (message is null or char_length(message) <= 4000),
  status      text not null default 'new' check (status in ('new', 'reviewing', 'booked', 'passed')),
  notes       text,
  check (email is not null or phone is not null)
);
create index if not exists site_booking_requests_new_idx on public.site_booking_requests (created_at desc);
alter table public.site_booking_requests enable row level security;

alter table public.site_event_pages enable row level security;
alter table public.site_events enable row level security;
alter table public.site_job_applications enable row level security;

-- ---------- the website's own login ----------
do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'rr_site_app') then
    create role rr_site_app login password 'REPLACE_WITH_SITE_DB_PASSWORD';
  else
    alter role rr_site_app login password 'REPLACE_WITH_SITE_DB_PASSWORD';
  end if;
end $$;

grant usage on schema public to rr_site_app;
grant select, insert, update, delete on public.site_event_pages, public.site_events to rr_site_app;
grant select, insert, update on public.site_job_applications to rr_site_app;
grant select, insert, update on public.site_booking_requests to rr_site_app;
grant select on public.site_event_closures to rr_site_app;

-- Venio reads closures from here (only if Venio's login exists in this database).
do $$
begin
  if exists (select 1 from pg_roles where rolname = 'rr_events_app') then
    execute 'grant select on public.site_event_closures to rr_events_app';
    execute 'grant select on public.site_events to rr_events_app';
    execute 'drop policy if exists site_events_venio_read on public.site_events';
    execute 'create policy site_events_venio_read on public.site_events for select to rr_events_app using (true)';
  end if;
end $$;

-- The "which space?" question reads Venio's list of spaces (names only matter).
do $$
begin
  if to_regclass('public.spaces') is not null then
    execute 'grant select on public.spaces to rr_site_app';
  end if;
end $$;

-- RLS: the website role sees everything in its own tables (it is the only client; the public never
-- talks to the database directly). No policies for anon/authenticated, so the public API can't read them.
drop policy if exists site_event_pages_app on public.site_event_pages;
create policy site_event_pages_app on public.site_event_pages for all to rr_site_app using (true) with check (true);
drop policy if exists site_events_app on public.site_events;
create policy site_events_app on public.site_events for all to rr_site_app using (true) with check (true);
drop policy if exists site_job_applications_app on public.site_job_applications;
create policy site_job_applications_app on public.site_job_applications for all to rr_site_app using (true) with check (true);
drop policy if exists site_booking_requests_app on public.site_booking_requests;
create policy site_booking_requests_app on public.site_booking_requests for all to rr_site_app using (true) with check (true);

commit;
